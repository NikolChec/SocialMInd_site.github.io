function applyLanguage(lang) {
  const safeLang = translations[lang] ? lang : "en";
  const dict = translations[safeLang];

  document.documentElement.lang = safeLang;
  document.documentElement.dir = safeLang === "he" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (Object.prototype.hasOwnProperty.call(dict, key)) {
      el.textContent = dict[key];
    } else {
      const inline = el.getAttribute(`data-i18n-${safeLang}`);
      if (inline !== null) {
        el.textContent = inline;
      }
    }
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const attr = el.getAttribute("data-i18n-attr");
    const key = el.getAttribute("data-i18n-attr-key");
    const inlineValue = el.getAttribute(`data-i18n-${safeLang}`);
    const value = key && Object.prototype.hasOwnProperty.call(dict, key)
      ? dict[key]
      : inlineValue;
    if (attr && value !== null && value !== undefined) {
      el.setAttribute(attr, value);
    }
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const isActive = btn.dataset.lang === safeLang;
    btn.classList.toggle("active", isActive);
    btn.setAttribute("aria-pressed", isActive ? "true" : "false");
  });

  localStorage.setItem(STORAGE_KEY, safeLang);
  window.dispatchEvent(new CustomEvent("socialmind:languagechange", {
    detail: { lang: safeLang }
  }));
}

function initI18n() {
  const saved = localStorage.getItem(STORAGE_KEY) || "en";

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      applyLanguage(btn.dataset.lang);
    });
  });

  applyLanguage(saved);
}

window.addEventListener("DOMContentLoaded", initI18n);
